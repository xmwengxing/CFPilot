#!/usr/bin/env node
/**
 * 从唯一数据源 packages/cli/assets/sources-builtin.json 生成 CLI / Go 两侧常量。
 *
 * 为什么要生成：内置来源清单在 CLI（TypeScript）与桌面版（Go）各有一份，
 * 手抄必然漂移。用同一份 JSON + 同一个 JSON 字符串常量，两边 json.Unmarshal /
 * JSON.parse 即可，连字段顺序都不用对齐。
 *
 *   node scripts/gen-builtin-sources.mjs           生成
 *   node scripts/gen-builtin-sources.mjs --check   只校验，不改文件（接入 verify）
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceFile = join(root, 'packages/cli/assets/sources-builtin.json')
const tsOut = join(root, 'packages/cli/src/sources/builtin.generated.ts')
const goOut = join(root, 'packages/desktop/internal/scan/builtin_sources_generated.go')

const data = JSON.parse(readFileSync(sourceFile, 'utf8'))
const rows = data.sources

// 唯一的 id 是数据源的主键，重复会让「编辑 / 删除」命中错误条目
const ids = new Set()
for (const row of rows) {
  if (!Array.isArray(row) || row.length !== 3) {
    console.error('每条来源必须是 [id, name, url]')
    process.exit(1)
  }
  const [id, name, url] = row
  if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) {
    console.error(`来源 id 非法：${id}`)
    process.exit(1)
  }
  if (ids.has(id)) {
    console.error(`来源 id 重复：${id}`)
    process.exit(1)
  }
  ids.add(id)
  if (!/^https:\/\//.test(url)) {
    console.error(`来源 URL 必须是 https：${url}`)
    process.exit(1)
  }
  if (!name || !name.trim()) {
    console.error(`来源 ${id} 缺少名称`)
    process.exit(1)
  }
}

const configs = rows.map(([id, name, url]) => ({
  id,
  name,
  type: 'custom-url',
  url,
  mirrors: [],
  // 内置来源默认停用：链接会失效，开箱就同步会在第一次使用中撞 404。
  // 数据源页可启用；「加载数据源清单」弹窗不受 enabled 限制。
  enabled: false,
  intervalHours: 6,
  etag: '',
  lastModified: '',
  lastSyncAt: 0,
  lastError: '',
  failCount: 0,
  query: '',
  // 与 CLI / Go 的 normalizeSource 默认值一致：写 0 会在首次读回时被改成 200，
  // 导致「内容未变不写」首帧多一次无意义落盘（KV/磁盘 I/O 都该省）。
  maxResults: 200,
}))

const json = JSON.stringify(configs)
const tsContent = `// 本文件由 scripts/gen-builtin-sources.mjs 从 packages/cli/assets/sources-builtin.json 生成，请勿手改
export const BUILTIN_SOURCES_JSON = ${JSON.stringify(json)}
export const BUILTIN_SOURCES_COUNT = ${configs.length}
`

const goContent = `// Code generated by scripts/gen-builtin-sources.mjs; DO NOT EDIT.
// Source of truth: packages/cli/assets/sources-builtin.json
package scan

import "encoding/json"

const builtinSourcesJSON = \`${json}\`

// BuiltinSources 返回随版本内置的数据源清单。
// 只在配置文件不存在时用于播种；保存过一次之后以用户文件为准。
func BuiltinSources() []SourceConfig {
	var out []SourceConfig
	if err := json.Unmarshal([]byte(builtinSourcesJSON), &out); err != nil {
		return nil
	}
	return out
}

// BuiltinSourcesCount 供静态一致性校验使用。
const BuiltinSourcesCount = ${configs.length}
`

const checkOnly = process.argv.includes('--check')
const outputs = [
  [tsOut, tsContent],
  [goOut, goContent],
]

let stale = false
for (const [file, content] of outputs) {
  let current = ''
  try {
    current = readFileSync(file, 'utf8')
  } catch {
    /* 文件不存在视为需要生成 */
  }
  if (current === content) continue
  stale = true
  if (!checkOnly) writeFileSync(file, content)
}

if (checkOnly) {
  if (stale) {
    console.error('FAIL  内置来源生成物与 sources-builtin.json 不一致，请运行 node scripts/gen-builtin-sources.mjs')
    process.exit(1)
  }
  console.log(`PASS  内置来源生成物一致（${configs.length} 条，CLI / Go 同源）`)
} else {
  console.log(`[builtin-sources] ${configs.length} 条 → CLI / Go 生成物已更新`)
}
